import Testing
@testable import Website

/**
Checks component scripts against Swift metadata, rendered DOM, and encoded configuration, without a JavaScript build step.
*/
struct ScriptTypeTests {
	private static let compiler = Project.website.root.appending(path: "node_modules/typescript/bin/tsc")

	private static var checksScriptTypes: Bool {
		ProcessInfo.processInfo.environment["CI"] != nil || compiler.exists
	}

	@Test(.temporaryDirectory, .enabled(if: Self.checksScriptTypes, "Run npm ci --ignore-scripts to check JavaScript types."))
	func `component scripts match Swift metadata and configuration`() async throws {
		let kinds = LiveFact.Kind.allCases.map { JSONEncoder.pageJSON($0.rawValue) }.joined(separator: " | ")
		let liveFactStates = LiveFact.States.allCases.map { JSONEncoder.pageJSON($0.rawValue) }.joined(separator: " | ")
		let copyButtonStates = CopyButton.States.allCases.map { JSONEncoder.pageJSON($0.rawValue) }.joined(separator: " | ")
		let awakeStates = AwakeStatus.States.allCases.map { JSONEncoder.pageJSON($0.rawValue) }.joined(separator: " | ")
		let icons = Icon.allCases.map { JSONEncoder.pageJSON($0.symbolID) }.joined(separator: " | ")
		let sharingMenu = OverflowMenu.appPage(try await App(), hasGuides: false)
		let declarations = """
		// Generated by ScriptTypeTests from Swift component metadata. Do not edit.
		export type LiveFactKind = \(kinds);
		export type LiveFactState = \(liveFactStates);
		export type CopyButtonState = \(copyButtonStates);
		export type AwakeStatusState = \(awakeStates);
		export type SiteIcon = \(icons);
		\(try Self.partDeclarations(for: LiveFact.Kind.allCases.map { LiveFact(kind: $0) }))
		\(try Self.partDeclarations(for: [AwakeStatus()]))
		\(try Self.partDeclarations(for: [OverflowMenu(label: "Actions", links: []), sharingMenu]))

		"""
		// Keep the declarations in the normal build directory, so editors can use the same tsconfig after a check.
		let declarationsFile = Project.website.root.appending(path: ".build/script-types.d.ts")
		try Data(declarations.utf8).write(to: declarationsFile, options: .atomic)

		let scripts = Project.website.root.appending(path: "Sources/Website/Components/Scripts")
		let liveFactSource = try String(contentsOf: scripts.appending(path: "LiveFact.js"), encoding: .utf8)
		let copyButtonSource = try String(contentsOf: scripts.appending(path: "CopyButton.js"), encoding: .utf8)
		let awakeSource = try String(contentsOf: scripts.appending(path: "AwakeStatus.js"), encoding: .utf8)
		let overflowSource = try String(contentsOf: scripts.appending(path: "OverflowMenu.js"), encoding: .utf8)
		let configuration = Project.website.root.appending(path: "tsconfig.json")
		let directory = try URL.temporaryDirectory()
		var checks: [(name: String, source: String?, diagnostic: String?)] = [
			("scripts", nil, nil),
			("optional-share", overflowSource.replacing("if (shareOption && navigator.canShare?.(sharedPage(this)))", with: "if (navigator.canShare?.(sharedPage(this)))"), "TS18049"),
			("share-part-type", overflowSource.replacing("shareOption.hidden = false", with: "shareOption.href = 'https://example.com'"), "TS2339"),
			("share-part-name", overflowSource.replacing("OverflowMenuParts['share']", with: "OverflowMenuParts['shrae']"), "TS2339"),
			("part-name", liveFactSource.replacing("detail: detailPart", with: "detial: detailPart"), "TS2339"),
			("part-type", liveFactSource.replacing("valuePart.textContent = value", with: "valuePart.value = value"), "TS2339"),
			("missing-kind", liveFactSource.replacing("\t'utc-time': utcTime,\n", with: ""), "TS2741"),
			("live-fact-state", liveFactSource.replacing("('shown')", with: "('shown'.toUpperCase())"), "TS1360"),
			("copy-button-state", copyButtonSource.replacing("('copied')", with: "('copied'.toUpperCase())"), "TS1360"),
			("nested-config-key", awakeSource.replacing("status.beforeHour", with: "status.beforeHours"), "TS2551"),
			("awake-part-type", awakeSource.replacing("textPart.textContent = text", with: "textPart.value = text"), "TS2339"),
		]

		let helperImport = """
		// @ts-check
		import {clockTime, untilNextMinute, cloneTemplate, parts, scriptData, copy, share} from '/scripts/dom.js';

		"""
		let helperChecks: [(name: String, source: String, diagnostic: String?)] = [
			("helper-inputs", "clockTime(new Date()); clockTime(new Date(), 'UTC'); untilNextMinute(new Date()); cloneTemplate(document.createElement('template')); parts(document.body); copy('Text', document.body); share({url: 'https://example.com'});", nil),
			("clock-input", "clockTime('2026-01-01');", "TS2345"),
			("minute-input", "untilNextMinute(10);", "TS2345"),
			("template-input", "cloneTemplate(document.createElement('div'));", "TS2740"),
			("parts-input", "parts(document);", "TS2740"),
			("copy-input", "copy(42, document.body);", "TS2345"),
			("share-input", "share({url: 42});", "TS2322"),
			("untyped-json", "scriptData('data').missing;", "TS2571"),
			("missing-part", "parts(document.body).then.textContent;", "TS2532"),
			("indexed-value", "const dates = [new Date()]; clockTime(dates[1]);", "TS2345"),
			("optional-property", "/** @type {{zone?: string}} */ const options = {zone: undefined};", "TS2375"),
		]
		checks += helperChecks.map { ($0.name, helperImport + $0.source, $0.diagnostic) }

		let configPrefix = """
		// @ts-check
		/** @satisfies {import(\(JSONEncoder.pageJSON(scripts.appending(path: "AwakeStatus.js").path(percentEncoded: false)))).AwakeStatusConfig} */
		export const configuration =
		"""

		for offset in [0, 420, -210] {
			let config = try #require(AwakeStatus(utcOffsetMinutes: offset).config)
			// These exact type witnesses keep the fixed contract from accepting optional fields just because a fixture has values.
			let _: (Int, [AwakeStatus.Status]) = (config.utcOffsetMinutes, config.statuses)
			try #require(!config.statuses.isEmpty)

			for status in config.statuses {
				let _: (AwakeStatus.States, Icon, String, Int) = (status.state, status.icon, status.text, status.beforeHour)
			}

			for hour in 0..<24 {
				#expect(config.statuses.contains { hour < $0.beforeHour }, "Every hour must have a display outcome.")
			}

			checks.append(("config-\(offset)", configPrefix + JSONEncoder.pageJSON(config) + ";", nil))
		}

		let config = try #require(AwakeStatus().config)
		let payload = try #require(try JSONSerialization.jsonObject(with: JSONEncoder().encode(config)) as? [String: Any])
		let mutations: [(name: String, key: String, value: Any?, diagnostic: String)] = [
			("config-number", "beforeHour", "three", "TS2322"),
			("config-missing", "beforeHour", nil, "TS2741"),
			("config-extra", "beforeHours", 3, "TS2353"),
			("config-state", "state", "unknown-state", "TS2322"),
			("config-icon", "icon", "unknown-icon", "TS2322"),
		]

		for mutation in mutations {
			var changed = payload
			var statuses = try #require(payload["statuses"] as? [[String: Any]])
			try #require(!statuses.isEmpty)
			statuses[0][mutation.key] = mutation.value
			changed["statuses"] = statuses
			let json = String(decoding: try JSONSerialization.data(withJSONObject: changed, options: .sortedKeys), as: UTF8.self)
			checks.append((mutation.name, configPrefix + json + ";", mutation.diagnostic))
		}

		for check in checks {
			let project: URL

			if let source = check.source {
				let input = directory.appending(path: "\(check.name).js")
				try Data(source.utf8).write(to: input)
				project = directory.appending(path: "\(check.name).json")
				let options = """
				{"extends": \(JSONEncoder.pageJSON(configuration.path(percentEncoded: false))), "files": [\(JSONEncoder.pageJSON(input.path(percentEncoded: false)))]}
				"""
				try Data(options.utf8).write(to: project)
			} else {
				project = configuration
			}

			let result = try await Subprocess.run(
				.name("node"),
				arguments: Arguments([Self.compiler.path(percentEncoded: false), "--project", project.path(percentEncoded: false)]),
				output: .string(limit: 1_000_000),
				error: .string(limit: 1_000_000)
			)
			let diagnostics = [result.standardOutput, result.standardError].compactMap(\.self).joined(separator: "\n")

			if let diagnostic = check.diagnostic {
				#expect(!result.terminationStatus.isSuccess, "The compiler must reject \(check.name).")
				#expect(diagnostics.contains(diagnostic), "Expected \(diagnostic) for \(check.name): \(diagnostics)")
			} else {
				#expect(result.terminationStatus.isSuccess, "\(diagnostics)")
			}
		}
	}

	/**
	Generates flat HTML part types from rendered variants. A part absent from any variant is optional. Every declared part must appear, at most once per variant and always with the same tag.
	*/
	private static func partDeclarations<Element: ScriptedElement>(for variants: [Element]) throws -> String {
		let declaredParts = Set(Element.Parts.allCases.map(\.rawValue))
		let partPattern = /<([a-z][a-z0-9-]*)\b[^>]*\bdata-part="([^"]+)"/
		var partTags: [String: String] = [:]
		var commonParts = declaredParts
		try #require(!variants.isEmpty)

		for variant in variants {
			let html = variant.render()
			let matches = html.matches(of: partPattern)
			let tags = try Dictionary(grouping: matches, by: { String($0.2) }).mapValues { matches in
				try #require(matches.count == 1, "Each part must have one element per variant.")
				return try #require(matches.first.map { String($0.1) })
			}
			#expect(Set(tags.keys).isSubset(of: declaredParts))
			commonParts.formIntersection(tags.keys)

			for (part, tag) in tags {
				if let previous = partTags[part] {
					#expect(previous == tag, "Every appearance of a part must have the same element type.")
				}

				partTags[part] = tag
			}
		}

		#expect(Set(partTags.keys) == declaredParts, "Every declared part must appear in a rendered variant.")
		let properties = try Element.Parts.allCases.map { part in
			let name = JSONEncoder.pageJSON(part.rawValue)
			let optional = commonParts.contains(part.rawValue) ? "" : "?"
			let tag = JSONEncoder.pageJSON(try #require(partTags[part.rawValue]))
			return """
				/**
				The \(part.rawValue) part rendered by \(Element.self).
				@example
				parts[\(name)]?.textContent;
				*/
				readonly \(name)\(optional): HTMLElementTagNameMap[\(tag)];
			"""
		}.joined(separator: "\n")
		return """
		export type \(Element.self)Parts = {
		\(properties)
		};
		"""
	}
}
